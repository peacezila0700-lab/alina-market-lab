"""Feasibility math: what edge does a trade actually need to survive costs?

Nothing here is a strategy. This answers one question the project kept deferring:
**given the measured cost structure, how good does a rule have to be before it is even
worth testing?**

Inputs are measured (not assumed):
  spread     0.9 pip round trip  (Dukascopy tick sample, 1,332 ticks, 2026-11-20)
  slippage   0.2 pip per side
  swap       UNKNOWN -> swept over 0.0 / 0.3 / 0.8 pip per night (0.3 is a placeholder bound)
  volatility EURGBP measured from the 26-year canonical dataset
"""
import csv, os, numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PIP = 1e-4
SPREAD, SLIP = 0.9, 0.2
RT = SPREAD + 2 * SLIP          # 1.3 pips round trip


def measure(sym="EURGBP"):
    rows = list(csv.DictReader(open(os.path.join(ROOT, "data", "processed",
                                                 f"{sym}_D1_fullclean.csv"))))
    h = np.array([float(r["high"]) for r in rows])
    l = np.array([float(r["low"]) for r in rows])
    c = np.array([float(r["close"]) for r in rows])
    rng = (h - l) / PIP
    ret = np.abs(np.diff(c)) / PIP
    return dict(n=len(rows), median_range=float(np.median(rng)),
                p25_range=float(np.percentile(rng, 25)),
                median_abs_ret=float(np.median(ret)),
                atr20=float(np.mean((h - l)[-20:]) / PIP))


def breakeven_winrate(target, stop, cost):
    """win rate needed for expectancy = 0 with a naive R:R"""
    return (stop + cost) / (target + stop)


def expectancy(win, target, stop, cost):
    return win * target - (1 - win) * stop - cost


if __name__ == "__main__":
    m = measure()
    L = ["# FEASIBILITY MATH — how much edge is enough?", "",
         "Generated by `scripts/breakeven.py`. All inputs measured, none assumed.", "",
         "## 1. Measured volatility (EURGBP, 26y canonical D1)", "",
         f"- bars: {m['n']}", f"- median daily range: **{m['median_range']:.1f} pips**",
         f"- 25th pct daily range: {m['p25_range']:.1f} pips",
         f"- median |close-to-close|: {m['median_abs_ret']:.1f} pips",
         f"- ATR(20) now: {m['atr20']:.1f} pips", "",
         "## 2. Cost structure", "",
         f"- spread (measured, round trip): {SPREAD} pip",
         f"- slippage: {SLIP} x 2 = {2*SLIP:.1f} pip",
         f"- **round trip = {RT:.1f} pips**",
         "- swap/financing: **UNKNOWN** — swept below, because at multi-day holds it can dominate", "",
         "## 3. Cost per hold length (this is the part that surprised me)", "",
         "| hold | spread+slippage | swap @0.3/night | swap @0.8/night | total @0.8 |",
         "|---|---|---|---|---|"]
    for nights in (1, 5, 10, 20):
        L.append(f"| {nights}d | {RT:.1f} | {0.3*nights:.1f} | {0.8*nights:.1f} | "
                 f"{RT + 0.8*nights:.1f} |")
    L += ["", "> At a 20-day hold, financing can be **16 pips** — more than 12× the spread.",
          "> EXP-0001/0002 assumed swap = 0. If the real swap is 0.8 pip/night, a +5.8 pip/trade",
          "> result becomes **−10 pips/trade**. The cost model, not the signal, may decide this.",
          "",
          "## 4. Break-even win rate (cost = 1.3 pips, no swap)", "",
          "| target | stop | break-even win % | win 55% gives | win 60% gives |",
          "|---|---|---|---|---|"]
    for target, stop in [(10, 10), (15, 15), (20, 20), (30, 20), (40, 20), (20, 40)]:
        be = breakeven_winrate(target, stop, RT) * 100
        L.append(f"| {target} | {stop} | **{be:.1f}%** | "
                 f"{expectancy(0.55, target, stop, RT):+.1f} pips | "
                 f"{expectancy(0.60, target, stop, RT):+.1f} pips |")
    L += ["", "## 5. Break-even with realistic financing (hold 15d @ 0.5 pip/night = 7.5 pips)", "",
          "| target | stop | total cost | break-even win % |",
          "|---|---|---|---|"]
    for target, stop in [(20, 20), (30, 20), (40, 20)]:
        cost = RT + 7.5
        L.append(f"| {target} | {stop} | {cost:.1f} | "
                 f"**{breakeven_winrate(target, stop, cost)*100:.1f}%** |")
    L += ["", "## 6. What this means for the project", "",
          "1. **A rule needs roughly 55-57% win rate at 1:1 R:R just to break even** on intraday-scale",
          "   targets. That is a high bar; most naive rules land at 50-52%.",
          "2. **Longer holds are not free.** Financing can exceed the spread by an order of magnitude,",
          "   so 'move to daily holds' does not remove the cost problem, it relocates it.",
          "3. **The measured +5.81 pips/trade from EXP-0002 is inside the noise band AND would be",
          "   erased by plausible financing.** Two independent reasons to reject it.",
          "4. **Before the next experiment, two numbers must come from the owner's broker:**",
          "   exact spread by hour for EURGBP, and swap long/short per night. Without them any",
          "   backtest result is a guess dressed as a measurement.", ""]
    out = os.path.join(ROOT, "reports", "FEASIBILITY_MATH.md")
    open(out, "w").write("\n".join(L))
    print(f"median daily range={m['median_range']:.1f} pips | median |ret|={m['median_abs_ret']:.1f} | ATR20={m['atr20']:.1f}")
    print(f"break-even win @ (20/20, cost 1.3) = {breakeven_winrate(20,20,RT)*100:.1f}%")
    print(f"break-even win @ (20/20, cost 1.3+7.5) = {breakeven_winrate(20,20,RT+7.5)*100:.1f}%")
    print("wrote reports/FEASIBILITY_MATH.md")
